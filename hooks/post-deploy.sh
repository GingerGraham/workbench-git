#!/usr/bin/env bash
# hooks/post-deploy.sh — workbench-git
# Runs once, on this module's first successful sync (run_on: initial, per
# .dotfiles-sync.yml), gated by the machine having registered this module
# with --allow-hooks (docs/module-authoring.md#hooks, in workbench-core).
#
# Replaces what Ansible's gitconfig.j2/projects.yml.j2 templating did in
# workbench-precursor: scaffolds the on-machine manifest and the global
# git config plumbing that points at this module's deployed static content
# (files/attributes, files/ignore). It deliberately does NOT set git
# identity (user.name/user.email) — that's interactive-only, via
# git-setup-identity in shell/git.sh, since no hook can safely guess it.
set -uo pipefail

# GIT_CONFIG_DIR holds this module's own *generated, runtime* state
# (projects.yml/project-includes/profiles/) — never touched by
# workbench-core's manifest denylist since it's created here, not by a
# deploy: entry.
GIT_CONFIG_DIR="${HOME}/.config/git"
MANIFEST="${GIT_CONFIG_DIR}/projects.yml"
INCLUDES="${GIT_CONFIG_DIR}/project-includes"
PROFILES_DIR="${GIT_CONFIG_DIR}/profiles"
LOCAL_INC="${PROFILES_DIR}/local.inc"

# STATIC_DIR is where this module's deploy: entries actually land
# (.dotfiles-sync.yml) — deliberately NOT under ~/.config/git/, which is on
# workbench-core's dest denylist (contracts/manifest-spec.md §dest
# validation). Deliberately NOT $XDG_DATA_HOME-aware: deploy[].dest is
# always anchored at ~/ (i.e. $HOME) per contracts/manifest-spec.md §dest
# validation, regardless of $XDG_DATA_HOME, so this must match literally.
# Keep this in sync with .dotfiles-sync.yml's deploy[].dest and
# shell/git.sh's git-setup-identity.
STATIC_DIR="${HOME}/.local/share/workbench/modules/git/files"

mkdir -p "${PROFILES_DIR}"

if [[ ! -f "${MANIFEST}" ]]; then
    cat > "${MANIFEST}" <<'EOF'
# Git projects manifest — source of truth for the live system.
#
# Created once by workbench-git's post-deploy hook; never overwritten
# afterwards. Updated live by: git-add-project, git-update-project,
# git-remove-project.

projects_base: ~/Projects
projects: []
EOF
    echo "[INFO] workbench-git: created ${MANIFEST}"
fi

if [[ ! -f "${INCLUDES}" ]]; then
    cat > "${INCLUDES}" <<'EOF'
# Generated by workbench-git — do not edit directly.
# To add a project: git-add-project <context> <provider> <email>
EOF
    echo "[INFO] workbench-git: created ${INCLUDES}"
fi

[[ -f "${LOCAL_INC}" ]] || { touch "${LOCAL_INC}"; echo "[INFO] workbench-git: created ${LOCAL_INC}"; }

# Set a single-valued global git key only when it is unset, already ours,
# or points at a byte-identical copy of ours (a dotfiles-era path) — never
# replace a value the user chose. Interim, docs/decisions-log.md D81 Phase 1
# in workbench-core; Phase 2 moves this into a core-owned gitconfig layer.
_wb_git_set_unless_user() {
    local key="$1" value="$2" current current_path
    current="$(git config --global --get "${key}" 2>/dev/null)"
    current_path="${current/#\~/${HOME}}"
    if [[ -z "${current}" || "${current_path}" == "${value}" ]] \
        || { [[ -f "${current_path}" && -f "${value}" ]] && cmp -s "${current_path}" "${value}"; }; then
        git config --global "${key}" "${value}"
        return 0
    fi
    echo "[INFO] workbench-git: keeping your ${key} (${current}); workbench's is at ${value} if you want to merge it" >&2
}

# Remove only workbench's own include.path entry, then re-add it — never
# the user's own include.path lines (security review L6). --fixed-value:
# git >= 2.30. Exit 5 ("no entry matches") is expected on the first run,
# before workbench has ever added this path; any other nonzero exit (e.g.
# --fixed-value unsupported on git < 2.30) is a real failure and must not
# be masked, or this would silently fall through to --add and duplicate
# the entry on every run.
_git_unset_own_include() {
    local path="$1" rc
    git config --global --fixed-value --unset-all include.path "${path}" 2>/dev/null
    rc=$?
    if [[ ${rc} -ne 0 && ${rc} -ne 5 ]]; then
        echo "[ERROR] workbench-git: 'git config --fixed-value --unset-all' failed (exit ${rc}) for include.path ${path} — is git >= 2.30 installed?" >&2
        return 1
    fi
    return 0
}

# Point global git config at this module's deployed static content and the
# two [include] files above — idempotent, safe to re-run.
_wb_git_set_unless_user core.excludesfile "${STATIC_DIR}/ignore"
_wb_git_set_unless_user core.attributesfile "${STATIC_DIR}/attributes"
_git_unset_own_include "${LOCAL_INC}" || exit 1
_git_unset_own_include "${INCLUDES}" || exit 1
git config --global --add include.path "${LOCAL_INC}"
git config --global --add include.path "${INCLUDES}"

if [[ -z "$(git config --global user.email 2>/dev/null)" ]]; then
    cat <<'EOF'

workbench-git deployed. Base config (excludesfile/attributesfile/includes)
is wired, but no git identity is set yet. Run:

  git-setup-identity

to configure user.name/user.email (and, optionally, a default GPG signing
key) interactively.

EOF
fi
